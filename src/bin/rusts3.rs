use std::net::SocketAddr;
use std::sync::Arc;

use clap::{Parser, Subcommand};
use rust_s3_server::server::{config::AppConfig, logging::init_logging, serve, S3HttpConfig};

/// S3-compatible single-node S3 server.
///
/// All configuration lives in a YAML file.
/// Run `rusts3 init` to generate a documented `config.yaml` in the current
/// directory, then `rusts3 run` to start the server.
#[derive(Parser, Debug)]
#[command(name = "rusts3", version)]
struct Cli {
    #[command(subcommand)]
    command: Option<Command>,

    /// Legacy form: path to config.yaml. Prefer `rusts3 run -c FILE`.
    #[arg(short = 'c', long, value_name = "FILE")]
    config: Option<String>,

    /// Legacy form: write a default config. Prefer `rusts3 init`.
    #[arg(long)]
    init: bool,
}

#[derive(Subcommand, Debug)]
enum Command {
    /// Start the S3 server.
    Run {
        /// Path to config.yaml.
        #[arg(short = 'c', long, value_name = "FILE", default_value = "config.yaml")]
        config: String,
    },
    /// Generate a bcrypt hash for a built-in console password.
    #[command(name = "genpassword")]
    GenPassword {
        /// Bcrypt cost factor.
        #[arg(long, default_value_t = bcrypt::DEFAULT_COST)]
        cost: u32,
        /// Password value. Omit to enter it securely at the prompt.
        #[arg(long)]
        password: Option<String>,
    },
    /// Verify a cleartext console password against a bcrypt hash.
    #[command(name = "verifypassword")]
    VerifyPassword {
        /// Bcrypt hash. Omit to enter it at the prompt.
        hash: Option<String>,
        /// Cleartext value. Omit to enter it securely at the prompt.
        #[arg(long)]
        cleartext: Option<String>,
    },
    /// Parse and validate a configuration file without starting the server.
    Validate {
        #[arg(short = 'c', long, value_name = "FILE", default_value = "config.yaml")]
        config: String,
    },
    /// Write a documented config.yaml in the current directory.
    Init,
}

/// Header prepended to the config `init` writes. The body below it is the
/// serialization of [`AppConfig::default`], so the generated file is always an
/// exact, complete image of the parser's defaults — no hand-maintained template
/// to drift out of sync. See `AppConfig` (src/server/config.rs) and
/// `StorageConfig` (src/storage/config.rs) for per-field documentation.
const CONFIG_HEADER: &str = "\
# rusts3 configuration
# Generated by: rusts3 init
# Start the server with: rusts3 run -c config.yaml
#
# This file lists every supported option set to its default value. Field docs
# live in the source config types; edit values here and re-run the server.
# Note: auth.enabled defaults to false, which leaves the S3 API fully open.
";

#[tokio::main]
async fn main() -> Result<(), Box<dyn std::error::Error>> {
    let cli = Cli::parse();
    match cli.command {
        Some(Command::Run { config }) => run_server(AppConfig::from_file(&config)?).await,
        Some(Command::GenPassword { cost, password }) => {
            let password = match password {
                Some(value) => value,
                None => {
                    let first = rpassword::prompt_password("Password: ")?;
                    let second = rpassword::prompt_password("Confirm password: ")?;
                    if first != second {
                        return Err("passwords do not match".into());
                    }
                    first
                }
            };
            println!("{}", bcrypt::hash(password, cost)?);
            Ok(())
        }
        Some(Command::VerifyPassword { hash, cleartext }) => {
            let hash = match hash {
                Some(value) => value,
                None => prompt_line("Bcrypt hash: ")?,
            };
            let cleartext = match cleartext {
                Some(value) => value,
                None => rpassword::prompt_password("Cleartext password: ")?,
            };
            if bcrypt::verify(cleartext, hash.trim())? {
                println!("password matches");
                Ok(())
            } else {
                eprintln!("password does not match");
                std::process::exit(1);
            }
        }
        Some(Command::Validate { config }) => {
            AppConfig::from_file(&config)?;
            println!("configuration is valid: {config}");
            Ok(())
        }
        Some(Command::Init) => write_default_config(),
        None if cli.init => write_default_config(),
        None => {
            let cfg = match cli.config {
                Some(path) => AppConfig::from_file(&path)?,
                None => AppConfig::default(),
            };
            run_server(cfg).await
        }
    }
}

fn write_default_config() -> Result<(), Box<dyn std::error::Error>> {
    let path = "config.yaml";
    if std::path::Path::new(path).exists() {
        return Err(format!(
            "{path} already exists — remove it first if you want to regenerate it"
        )
        .into());
    }
    let contents = format!("{CONFIG_HEADER}{}", AppConfig::default().to_yaml()?);
    std::fs::write(path, contents)?;
    println!("Wrote {path}. Edit it, then run: rusts3 run -c {path}");
    Ok(())
}

fn prompt_line(prompt: &str) -> Result<String, Box<dyn std::error::Error>> {
    use std::io::Write;
    print!("{prompt}");
    std::io::stdout().flush()?;
    let mut value = String::new();
    std::io::stdin().read_line(&mut value)?;
    Ok(value.trim_end().to_string())
}

async fn run_server(cfg: AppConfig) -> Result<(), Box<dyn std::error::Error>> {

    init_logging(&cfg.logging)?;

    let address: SocketAddr =
        format!("{}:{}", cfg.server.bind_address, cfg.server.bind_port).parse()?;

    log::info!(
        "rusts3 starting on {address} base_dir={} auth={}",
        cfg.server.base_dir,
        if cfg.auth.enabled {
            "enabled"
        } else {
            "disabled"
        },
    );

    // `auth.enabled` defaults to false, so an omitted/incomplete `auth:` section
    // silently boots a fully open server. Make that impossible to miss — and
    // shout louder when credentials are configured but auth is off, which is
    // almost certainly a misconfiguration.
    if !cfg.auth.enabled {
        let has_creds = !cfg.auth.credentials.is_empty() || !cfg.auth.users.is_empty();
        if has_creds {
            log::warn!(
                "SECURITY: auth.enabled is FALSE but credentials are configured — the S3 API \
                 is UNAUTHENTICATED and accepts ALL requests. Set `auth.enabled: true` to \
                 enforce them."
            );
        } else {
            log::warn!(
                "SECURITY: authentication is DISABLED — the S3 API accepts ALL requests without \
                 verification. Set `auth.enabled: true` (with credentials) to secure it."
            );
        }
    }

    serve(S3HttpConfig {
        address,
        root: cfg.server.base_dir.clone(),
        app_config: Arc::new(cfg),
    })
    .await
}

#[cfg(test)]
mod tests {
    use super::{Cli, Command};
    use clap::Parser;

    #[test]
    fn run_and_validate_default_to_config_yaml() {
        let run = Cli::try_parse_from(["rusts3", "run"]).unwrap();
        assert!(matches!(
            run.command,
            Some(Command::Run { config }) if config == "config.yaml"
        ));

        let validate = Cli::try_parse_from(["rusts3", "validate"]).unwrap();
        assert!(matches!(
            validate.command,
            Some(Command::Validate { config }) if config == "config.yaml"
        ));
    }

    #[test]
    fn password_subcommand_names_are_unhyphenated() {
        assert!(Cli::try_parse_from([
            "rusts3",
            "genpassword",
            "--password",
            "example-password"
        ])
        .is_ok());
        assert!(Cli::try_parse_from([
            "rusts3",
            "verifypassword",
            "$2b$12$abcdefghijklmnopqrstuuuuuuuuuuuuuuuuuuuuuuuuuuuuu",
            "--cleartext",
            "example-password"
        ])
        .is_ok());
    }
}
